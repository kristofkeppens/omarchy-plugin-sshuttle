"""Tests for the sudoers setup. ONLY fake binaries are used: SUDO_BIN, PKEXEC_BIN,
VISUDO_BIN and SSHUTTLE_BIN always point at scripts in a temp dir. The real
sudo/pkexec/visudo must never run, and nothing is written under /etc."""
import json
import time
import os
import stat
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import ctl  # noqa: E402

import pwd  # noqa: E402

USER = pwd.getpwuid(os.getuid()).pw_name
PYPATH = "/usr/lib/python3.14/site-packages"


def make_rule(path, user=None, alias="SSHUTTLEEF6", cmd=None, tail=""):
    """Shape of real sshuttle 2.0.0 --sudoers-no-modify output."""
    cmd = cmd or f"/usr/bin/env PYTHONPATH={PYPATH} {path} *"
    return (
        "\n# WARNING: If you intend to restrict a user to only running the\n"
        "# sshuttle command as root, THIS CONFIGURATION IS INSECURE.\n\n"
        "# This configuration was initially generated by the\n"
        "# 'sshuttle --sudoers-no-modify' command.\n\n"
        f"Cmnd_Alias {alias} = {cmd}\n\n"
        f"{user or USER} ALL=NOPASSWD: {alias}\n" + tail)


TARGET = "/etc/sudoers.d/sshuttle-panel"


def script(path, body):
    Path(path).write_text("#!/bin/sh\n" + body)
    os.chmod(path, 0o755)
    return str(path)


class SudoBase(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        t = Path(self.tmp.name)
        self.rule = make_rule(str(t / "sshuttle"))
        (t / "rule.txt").write_text(self.rule)
        ctl._sudo_cache.clear()
        self.addCleanup(ctl._sudo_cache.clear)
        self.pk_log = t / "pkexec.argv"
        self.pk_copy = t / "pkexec.rule"
        self.fakes = {
            "SSHUTTLE_BIN": script(t / "sshuttle", f"cat {t / 'rule.txt'}\n"),
            "VISUDO_BIN": script(t / "visudo", "exit 0\n"),
            # records argv one per line and its stdin
            "PKEXEC_BIN": script(
                t / "pkexec",
                f'for a in "$@"; do printf "%s\\n" "$a"; done > {self.pk_log}\n'
                f"cat > {self.pk_copy}\n"
                "exit 0\n"),
            "SUDO_BIN": script(t / "sudo", "exit 0\n"),
            "SSHUTTLE_PANEL_RUNTIME_DIR": str(t / "rt"),
            "SSHUTTLE_PANEL_CONFIG_DIR": str(t / "cfg"),
        }
        p = mock.patch.dict(os.environ, self.fakes)
        p.start()
        self.addCleanup(p.stop)

    def replace(self, name, body):
        script(self.fakes[name], body)

    def pk_argv(self):
        return self.pk_log.read_text().splitlines()


class TestSudoReady(SudoBase):
    def count_sudo(self):
        self.sudo_log = Path(self.tmp.name) / "sudo.calls"
        self.replace("SUDO_BIN", f'printf "%s\\n" "$*" >> {self.sudo_log}\nexit 0\n')

    def calls(self):
        return self.sudo_log.read_text().splitlines() if self.sudo_log.exists() else []

    def test_sudo_ready_true_and_false(self):
        self.assertTrue(ctl.sudo_ready(self.fakes["SSHUTTLE_BIN"]))
        ctl._sudo_cache.clear()
        self.replace("SUDO_BIN", "exit 1\n")
        self.assertFalse(ctl.sudo_ready(self.fakes["SSHUTTLE_BIN"]))

    def test_probe_argv_ends_with_firewall_and_has_no_star(self):
        self.count_sudo()
        ctl.sudo_ready(self.fakes["SSHUTTLE_BIN"])
        self.assertEqual(self.calls(), [
            f"-n -l /usr/bin/env PYTHONPATH={PYPATH} {self.fakes['SSHUTTLE_BIN']} --firewall"])
        self.assertNotIn("*", self.calls()[0])

    def test_cached_within_ttl_then_reprobes_after_expiry(self):
        self.count_sudo()
        with mock.patch.dict(os.environ, {"SSHUTTLE_PANEL_SUDO_TTL": "0.3"}):
            self.assertTrue(ctl.status()["sudo_ready"])
            self.assertTrue(ctl.status()["sudo_ready"])
            self.assertEqual(len(self.calls()), 1)
            time.sleep(0.4)
            ctl.status()
            self.assertEqual(len(self.calls()), 2)

    def test_cache_invalidated_by_setup(self):
        self.count_sudo()
        ctl.sudo_ready(self.fakes["SSHUTTLE_BIN"])
        self.assertTrue(ctl.setup_sudo()["ok"])
        self.assertEqual(len(self.calls()), 2)  # re-probed after install

    def test_timeout_is_false_and_status_does_not_hang(self):
        self.replace("SUDO_BIN", "exec sleep 10\n")
        with mock.patch.object(ctl, "PROBE_TIMEOUT", 0.3):
            t0 = time.monotonic()
            self.assertIs(ctl.status()["sudo_ready"], False)
            self.assertLess(time.monotonic() - t0, 3)

    def test_sshuttle_generation_hang_is_false(self):
        self.replace("SSHUTTLE_BIN", "exec sleep 10\n")
        with mock.patch.object(ctl, "PROBE_TIMEOUT", 0.3):
            self.assertFalse(ctl.sudo_ready(self.fakes["SSHUTTLE_BIN"]))

    def test_bad_rule_means_not_ready_and_no_sudo_call(self):
        self.count_sudo()
        (Path(self.tmp.name) / "rule.txt").write_text("Defaults !authenticate\n")
        self.assertFalse(ctl.sudo_ready(self.fakes["SSHUTTLE_BIN"]))
        self.assertEqual(self.calls(), [])

    def test_sudo_ready_false_when_sudo_missing_or_sshuttle_missing(self):
        with mock.patch.dict(os.environ, {"SUDO_BIN": "/nonexistent/sudo"}):
            self.assertFalse(ctl.sudo_ready(self.fakes["SSHUTTLE_BIN"]))
        self.assertFalse(ctl.sudo_ready("/nonexistent/sshuttle"))

    def test_status_reports_sudo_ready(self):
        self.assertIs(ctl.status()["sudo_ready"], True)
        ctl._sudo_cache.clear()
        self.replace("SUDO_BIN", "exit 1\n")
        self.assertIs(ctl.status()["sudo_ready"], False)


class TestParseRule(SudoBase):
    def parse(self, text):
        return ctl.parse_rule(text, USER, "/usr/bin/sshuttle")

    def good(self, **kw):
        return make_rule("/usr/bin/sshuttle", **kw)

    def test_accepts_real_fixture(self):
        self.assertEqual(self.parse(self.good()),
                         ["/usr/bin/env", f"PYTHONPATH={PYPATH}", "/usr/bin/sshuttle"])

    def test_rejects_each_bad_shape(self):
        cases = {
            "include": self.good(tail="#include /x\n"),
            "includedir": self.good(tail="#includedir /x\n"),
            "at-include": self.good(tail="@includedir /x\n"),
            "defaults": self.good(tail="Defaults !authenticate\n"),
            "all-all": self.good(tail="ALL ALL=(ALL) NOPASSWD: ALL\n"),
            "wrong user": self.good(user="mallory"),
            "extra rule": self.good(tail=f"{USER} ALL=NOPASSWD: SSHUTTLEEF6\n"),
            "other command": make_rule("/tmp/evil"),
            "star->ALL": self.good(cmd=f"/usr/bin/env PYTHONPATH={PYPATH} /usr/bin/sshuttle ALL"),
            "undefined alias": self.good().replace(f"NOPASSWD: SSHUTTLEEF6", "NOPASSWD: OTHER"),
            "second alias": self.good(tail="Cmnd_Alias X = /usr/bin/env PYTHONPATH=/a /usr/bin/sshuttle *\n"),
            "no rule line": self.good().replace(f"{USER} ALL=NOPASSWD: SSHUTTLEEF6", ""),
            "no alias": f"{USER} ALL=NOPASSWD: ALL\n",
            "crlf": self.good().replace("\n", "\r\n"),
            "nul": self.good() + "\0",
            "pythonpath metachar": self.good(cmd="/usr/bin/env PYTHONPATH=/a,/b /usr/bin/sshuttle *"),
        }
        for name, text in cases.items():
            with self.subTest(name):
                with self.assertRaises(ctl.ProfileError):
                    self.parse(text)

    def test_plain_comment_that_mentions_include_is_ok(self):
        self.parse(self.good(tail="# include is fine in a comment\n"))


class TestSetupSudo(SudoBase):
    def test_setup_sudo_installs_validated_rule(self):
        res = ctl.setup_sudo()
        self.assertTrue(res["ok"], res)
        argv = self.pk_argv()
        self.assertEqual(argv, ["install", "-m", "0440", "/dev/stdin", TARGET])
        self.assertEqual(self.pk_copy.read_bytes(), self.rule.encode())  # validated bytes via stdin

    def test_setup_sudo_passes_user_to_sshuttle(self):
        out = Path(self.tmp.name) / "sshuttle.argv"
        self.replace("SSHUTTLE_BIN", f'printf "%s\\n" "$@" > {out}\ncat {Path(self.tmp.name) / "rule.txt"}\n')
        ctl.setup_sudo()
        self.assertEqual(out.read_text().splitlines(),
                         ["--sudoers-no-modify", "--sudoers-user", USER])

    def test_setup_sudo_visudo_checks_the_file(self):
        out = Path(self.tmp.name) / "visudo.argv"
        self.replace("VISUDO_BIN", f'printf "%s\\n" "$@" > {out}\nexit 0\n')
        ctl.setup_sudo()
        a = out.read_text().splitlines()
        self.assertEqual(a[:2], ["-c", "-f"])
        self.assertNotIn(a[2], self.pk_argv())  # privileged step never sees the temp path

    def test_setup_sudo_rejects_when_visudo_fails(self):
        self.replace("VISUDO_BIN", "echo bad syntax >&2\nexit 1\n")
        res = ctl.setup_sudo()
        self.assertFalse(res["ok"])
        self.assertIn("validation", res["error"])
        self.assertFalse(self.pk_log.exists())  # pkexec never called

    def test_setup_sudo_cancelled(self):
        self.replace("PKEXEC_BIN", "exit 126\n")
        res = ctl.setup_sudo()
        self.assertFalse(res["ok"])
        self.assertEqual(res["error"], "Authorization cancelled")

    def test_setup_sudo_pkexec_other_failure(self):
        self.replace("PKEXEC_BIN", "exit 127\n")
        res = ctl.setup_sudo()
        self.assertFalse(res["ok"])
        self.assertIn("install failed", res["error"])

    def test_setup_sudo_sshuttle_failure_or_empty_output(self):
        self.replace("SSHUTTLE_BIN", "exit 2\n")
        self.assertFalse(ctl.setup_sudo()["ok"])
        self.replace("SSHUTTLE_BIN", "exit 0\n")  # empty rule
        self.assertFalse(ctl.setup_sudo()["ok"])
        self.assertFalse(self.pk_log.exists())

    def test_setup_sudo_rejects_dangerous_rules_without_visudo_or_pkexec(self):
        t = Path(self.tmp.name)
        visudo_log = t / "visudo.ran"
        self.replace("VISUDO_BIN", f"touch {visudo_log}\nexit 0\n")
        bad = [make_rule(self.fakes["SSHUTTLE_BIN"], tail="Defaults !authenticate\n"),
               make_rule(self.fakes["SSHUTTLE_BIN"], user="ALL"),
               "ALL ALL=(ALL) NOPASSWD: ALL\n",
               make_rule("/usr/bin/other")]
        for text in bad:
            (t / "rule.txt").write_text(text)
            res = ctl.setup_sudo()
            self.assertFalse(res["ok"])
            self.assertIn("unexpected sudoers rule", res["error"])
        self.assertFalse(visudo_log.exists())
        self.assertFalse(self.pk_log.exists())

    def test_setup_sudo_tempdir_failure_is_error_not_traceback(self):
        with mock.patch.object(ctl.tempfile, "mkdtemp", side_effect=PermissionError("denied")):
            res = ctl.setup_sudo()
        self.assertFalse(res["ok"])
        self.assertIn("temporary", res["error"])
        self.assertFalse(self.pk_log.exists())

    def test_setup_sudo_missing_binaries(self):
        for name in ("SSHUTTLE_BIN", "VISUDO_BIN", "PKEXEC_BIN"):
            with mock.patch.dict(os.environ, {name: "/nonexistent/x"}):
                self.assertFalse(ctl.setup_sudo()["ok"], name)
        self.assertFalse(self.pk_log.exists())

    def test_tempfile_and_dir_private_and_removed(self):
        out = Path(self.tmp.name) / "visudo.info"
        self.replace("VISUDO_BIN",
                     f'f="$3"; stat -c "%a" "$f" "$(dirname "$f")" > {out}; '
                     f'dirname "$f" >> {out}\nexit 0\n')
        ctl.setup_sudo()
        fmode, dmode, d = out.read_text().split()
        self.assertEqual((fmode, dmode), ("600", "700"))
        self.assertFalse(os.path.exists(d))

    def test_tempfile_modified_after_validation_cannot_influence_install(self):
        self.replace("VISUDO_BIN", 'printf "evil ALL=(ALL) NOPASSWD: ALL\\n" >> "$3"\nexit 0\n')
        res = ctl.setup_sudo()
        self.assertTrue(res["ok"], res)
        self.assertEqual(self.pk_copy.read_bytes(), self.rule.encode())

    def test_cli_setup_sudo(self):
        import io
        from contextlib import redirect_stdout
        buf = io.StringIO()
        with redirect_stdout(buf):
            rc = ctl.main(["setup-sudo"])
        self.assertEqual(rc, 0)
        self.assertTrue(json.loads(buf.getvalue())["ok"])
        self.replace("PKEXEC_BIN", "exit 126\n")
        with redirect_stdout(buf):
            self.assertEqual(ctl.main(["setup-sudo"]), 1)


if __name__ == "__main__":
    unittest.main()
